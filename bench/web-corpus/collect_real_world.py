SIZE_CLASS_BOUNDS = {
    "small": (1, 10_240),
    "medium": (10_240, 102_400),
    "large": (102_400, 8 * 1024 * 1024),
}


def digest(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def fetch(url: str) -> bytes:
    request = urllib.request.Request(
        url,
        headers={
            # Ask for the identity encoding: the corpus stores the resource,
            # not somebody else's compression of it.
            "Accept-Encoding": "identity",
            "User-Agent": "cubrim-web-corpus/2 (+https://cubrim.com)",
        },
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        if response.status != 200:
            raise RuntimeError(f"{url} returned {response.status}")
        return response.read()


def classify(byte_count: int) -> str:
    """Derive the size class. A sample outside every band is a real error."""
    for name, (low, high) in SIZE_CLASS_BOUNDS.items():
        if low <= byte_count < high:
            return name
    raise RuntimeError(f"{byte_count} bytes falls outside every size class")


def brotli_ratio(payload: bytes) -> float:
    """A realism signal, not a benchmark result.

    Corpus v1's defect was visible here: brotli-11 reached 0.0079 on its CSS
    sample. Real text resources land around 0.15-0.30, so a ratio far below
    that means the sample is synthetic rather than representative.
    """
    result = subprocess.run(
        ["brotli", "-q", "11", "-c"], input=payload, capture_output=True, check=True
    )
    return len(result.stdout) / len(payload)


def build(out_root: pathlib.Path, source_root: pathlib.Path, check_only: bool) -> int:
    payloads_dir = out_root / "payloads-v2"
    previous_manifest = out_root / "manifest.v2.json"
    pinned: dict[str, str] = {}
    if previous_manifest.is_file():
        for entry in json.loads(previous_manifest.read_text())["samples"]:
            pinned[entry["sample_id"]] = entry["sha256"]

    if not check_only:
        payloads_dir.mkdir(parents=True, exist_ok=True)

    samples = []
    failures = []

    for spec in LOCAL_SOURCES:
        source = source_root / spec["relative_path"]
        if not source.is_file():
            failures.append(f"{spec['sample_id']}: missing local source {source}")
            continue
        samples.append((spec, source.read_bytes(), f"payloads-v2/{source.name}"))

    for spec in FETCHED_SOURCES:
        try:
            payload = fetch(spec["url"])
        except Exception as error:  # noqa: BLE001 - reported, not swallowed
            failures.append(f"{spec['sample_id']}: fetch failed: {error}")
            continue
        suffix = {"html": ".html", "json-api": ".json"}[spec["media_family"]]
        samples.append((spec, payload, f"payloads-v2/{spec['sample_id']}{suffix}"))

    for spec in CARRIED_OVER:
        legacy = out_root / "payloads" / "inter-latin.medium.woff2"
        if not legacy.is_file():
            candidates = sorted((out_root / "payloads").glob("*.woff2"))
            if not candidates:
                failures.append(f"{spec['sample_id']}: no woff2 in corpus v1")
                continue
            legacy = candidates[0]
        samples.append((spec, legacy.read_bytes(), f"payloads-v2/{legacy.name}"))

    if failures:
        for failure in failures:
            print(f"FAIL: {failure}", file=sys.stderr)
        return 1

    records = []
    for spec, payload, relative in samples:
        sha = digest(payload)
        sample_id = spec["sample_id"]
        if sample_id in pinned and pinned[sample_id] != sha:
            print(
                f"FAIL: {sample_id} changed since it was pinned "
                f"({pinned[sample_id][:12]} -> {sha[:12]}). A corpus sample is "
                "immutable; add a new sample id instead.",
                file=sys.stderr,
            )
            return 1
        try:
            size_class = classify(len(payload))
        except RuntimeError as error:
            print(f"FAIL: {sample_id}: {error}", file=sys.stderr)
            return 1

        if not check_only:
            (out_root / relative).write_bytes(payload)

        records.append(
            {
                "sample_id": sample_id,
                "path": relative,
                "media_family": spec["media_family"],
                "media_type": spec["media_type"],
                "size_class": size_class,
                "byte_count": len(payload),
                "sha256": sha,
                "license_id": spec["license_id"],
                "attribution": spec["attribution"],
                "redistributable": True,
                "source_ref": spec["source_ref"],
            }
        )

    records.sort(key=lambda entry: entry["sample_id"])
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "corpus_key": "cubr0074-web-real-v2",
        "provenance": {
            "collector": "bench/web-corpus/collect_real_world.py",
            "policy": (
                "Real bytes served on the web that we may redistribute. No "
                "generated fixtures. Absent content types are recorded as gaps."
            ),
        },
        "gaps": MANIFEST_GAPS,
        "samples": records,
    }

    if not check_only:
        previous_manifest.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        checksums = out_root / "MANIFEST-V2.sha256"
        checksums.write_text(
            "".join(f"{entry['sha256']}  {entry['path']}\n" for entry in records)
        )

    print(f"{len(records)} real samples, {len(MANIFEST_GAPS)} recorded gaps")
    print(f"{'sample_id':40s} {'bytes':>8s} {'family':12s} {'class':7s} brotli-11")
    for entry, (_, payload, _) in zip(records, sorted(samples, key=lambda item: item[0]["sample_id"])):
        print(
            f"{entry['sample_id']:40s} {entry['byte_count']:8d} "
            f"{entry['media_family']:12s} {entry['size_class']:7s} "
            f"{brotli_ratio(payload):.4f}"
        )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=pathlib.Path)
    parser.add_argument(
        "--source-root",
        type=pathlib.Path,
        default=pathlib.Path("/home/dev/.worktrees"),
        help="root the local source paths resolve against",
    )
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    if shutil.which("brotli") is None:
        print("brotli is required for the realism signal", file=sys.stderr)
        return 2
    return build(args.out.resolve(), args.source_root.resolve(), args.check)


if __name__ == "__main__":
    sys.exit(main())
