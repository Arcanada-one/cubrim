#!/usr/bin/env python3
"""Assemble the CUBR-0074 real-world web corpus (v2).

Corpus v1 was project-authored: a generator produced fixtures that brotli-11
compresses to ratio 0.0079, a 126x compression no real stylesheet exhibits. Any
ratio measured against it says more about the generator than about the web, so
the decode-speed consilium made a real corpus Gate 1 for every claim.

This collector takes only bytes that are genuinely served on the web and that
we may legally redistribute:

* our own production site pages and API responses (Arcanada owns them, and they
  are already public);
* dist files and source maps from MIT-licensed packages, which are exactly the
  artefacts a real deployment ships;
* a real WOFF2 face under the SIL Open Font License, carried over from v1
  because it was already a real asset.

Two families are deliberately absent rather than faked. See MANIFEST_GAPS.

Every sample records where it came from, its licence, and its SHA-256. Sources
that must be fetched are pinned by digest on first collection, so a later run
that receives different bytes fails instead of silently redefining the corpus.

Usage:
  collect_real_world.py --out bench/web-corpus            # collect and write
  collect_real_world.py --out bench/web-corpus --check    # verify only
"""

